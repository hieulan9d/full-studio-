import { chromium } from 'playwright-core';
const b = await chromium.connectOverCDP('http://127.0.0.1:9333');
const page = b.contexts()[0].pages()[0];
page.on('request', r => { if (r.method()==='POST') console.log('REQ', r.url().slice(-30), (r.postData()||'').slice(0,300)); });
page.on('response', async r => { if (r.request().method()==='POST') console.log('RES', r.status(), (await r.text()).slice(0,300)); });
console.log(await page.evaluate(()=>{ const s=window.__te.store.get(); return {view:s.view, modal:!!s.modal, settings:s.settingsOpen, km:s.keymap.paste, sel:s.selection}; }));
await page.evaluate(()=>{ window.dispatchEvent(new KeyboardEvent('keydown',{key:'v',ctrlKey:true,bubbles:true})); });
await new Promise(r=>setTimeout(r,1200));
console.log(await page.evaluate(()=>({n:window.__te.store.get().project.clips.length, toast:document.querySelector('.toast')?.innerText})));
await b.close();
